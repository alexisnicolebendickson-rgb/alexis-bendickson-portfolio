# --- copy organized files + manifest ---
rows = []
for cat, code, album, pick, src in M:
    path = prior.get(src) or fmap.get(src)
    assert path and os.path.exists(path), f"missing {src}"
    cdir = os.path.join(OUT, cat); os.makedirs(cdir, exist_ok=True)
    dest = os.path.join(cdir, f"{code}_{album.replace(' ','-').replace('&','and')}_{pick.split(' ')[0]}.jpg")
    shutil.copy2(path, dest)
    rows.append([code, cat, album, pick, src, os.path.relpath(dest, OUT)])
with open(os.path.join(OUT, "manifest.csv"), "w", newline="") as fh:
    w = csv.writer(fh); w.writerow(["code","category","album","pick","source_ref","file"]); w.writerows(rows)
print(f"organized {len(rows)} files")

# --- contact sheets per category ---
try: font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 30)
except Exception: font = ImageFont.load_default()
TW, TH, LH, COLS = 300, 300, 44, 5
from collections import OrderedDict
cats = OrderedDict()
for r in M: cats.setdefault(r[0], []).append(r)
for cat, items in cats.items():
    rowsn = (len(items) + COLS - 1) // COLS
    sheet = Image.new("RGB", (COLS * TW, rowsn * (TH + LH)), "white")
    d = ImageDraw.Draw(sheet)
    for i, (c, code, album, pick, src) in enumerate(items):
        path = prior.get(src) or fmap.get(src)
        im = Image.open(path).convert("RGB")
        im.thumbnail((TW, TH))
        x, y = (i % COLS) * TW, (i // COLS) * (TH + LH)
        sheet.paste(im, (x + (TW - im.width) // 2, y + (TH - im.height) // 2))
        d.rectangle([x, y + TH, x + TW, y + TH + LH], fill=(30, 30, 30))
        d.text((x + 8, y + TH + 7), f"{code}  {album[:22]}", fill="white", font=font)
    outp = os.path.join(SHEETS, f"contact-{cat.lower().replace(' ','-')}.jpg")
    sheet.save(outp, quality=88)
    print("sheet:", outp, sheet.size, len(items), "thumbs")
